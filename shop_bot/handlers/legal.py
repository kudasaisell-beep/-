from aiogram import Router, F
from aiogram.types import CallbackQuery
from tg_utils import safe_answer, safe_edit

from keyboards import legal_kb, legal_back_kb

router = Router()


@router.callback_query(F.data == "legal_menu")
async def legal_menu(callback: CallbackQuery):
    text = (
        "📜 <b>Документы магазина</b>\n\n"
        "Перед использованием бота ознакомьтесь с документами:\n"
        "• <b>Политика конфиденциальности</b> — какие данные мы собираем и как их храним\n"
        "• <b>Пользовательское соглашение</b> — правила использования сервиса\n\n"
        "Продолжая пользоваться ботом, вы принимаете оба документа."
    )
    await safe_edit(callback, text, reply_markup=legal_kb)
    await safe_answer(callback)


